// Browser tests of the button Export HDL: one ZIP archive with the top level, its compile order, its constraints and
// the system file they were made from; a system with errors is not exported and the dialog says why.
import { test } from '@playwright/test';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { unzipStore } from '../../assets/composer/js/model/zip.js';
import { addBlock, expect, open, openExample, watch } from './helpers.mjs';

const golden = (/** @type {string} */ name) => readFileSync(new URL(`../golden/${name}`, import.meta.url), 'utf-8');
// the header names the hash of the file and the catalog, which change with every catalog
const stable = (/** @type {string} */ t) => t
  .replace(/Generated by .* from (\S+)/, 'Generated from $1')
  .replace(/(SHA-256 of \S+: )[0-9a-f]{64}/, '$1*')
  .replace(/(Block catalog: )[0-9a-f]+/, '$1*');

/** @type {string[]} */
let problems = [];

test.beforeEach(async ({ page }) => {
  problems = [];
  watch(page, problems);
});

test.afterEach(() => {
  expect(problems, problems.join('\n')).toEqual([]);
});

test('Export HDL downloads the top level, compile order and constraints with the system file', async ({ page }) => {
  await open(page);
  await openExample(page, 'SpaceWire RMAP target');
  const button = page.getByRole('button', { name: 'Export HDL', exact: true });
  await expect(button).toHaveAttribute('aria-disabled', 'false');
  const [download] = await Promise.all([page.waitForEvent('download'), button.click()]);
  expect(download.suggestedFilename()).toBe('spw_rmap_node_hdl.zip');
  const files = unzipStore(new Uint8Array(readFileSync(await download.path())));
  expect(files.map((f) => f.name)).toEqual([
    'spw_rmap_node.vhd', 'spw_rmap_node_compile_order.txt', 'spw_rmap_node.xdc', 'spw_rmap_node_top.xdc', 'spw_rmap_node.composer.json',
  ]);
  const text = (/** @type {string} */ name) => new TextDecoder().decode(files.find((f) => f.name === name)?.data);
  // the same files as the command line tool writes (golden files), apart from the header
  for (const name of ['spw_rmap_node.vhd', 'spw_rmap_node_compile_order.txt', 'spw_rmap_node.xdc', 'spw_rmap_node_top.xdc']) {
    expect(stable(text(name)), name).toBe(stable(golden(name)));
  }
  // the hash in the header is the hash of the system file in the archive
  const sha = createHash('sha256').update(text('spw_rmap_node.composer.json')).digest('hex');
  expect(text('spw_rmap_node.vhd')).toContain(`SHA-256 of spw_rmap_node.composer.json: ${sha}`);
  await expect(page.getByRole('status')).toContainText('Exported spw_rmap_node_hdl.zip');
});

test('a system with errors is not exported; the button says why', async ({ page }) => {
  await open(page);
  // an RMAP node alone: its packet ports must be served
  await addBlock(page, 'RMAP node');
  const button = page.getByRole('button', { name: 'Export HDL', exact: true });
  await expect(button).toHaveAttribute('aria-disabled', 'true');
  await expect(button).toHaveAttribute('title', /the system has \d+ errors? \(see Checks\)/);
  let downloads = 0;
  page.on('download', () => { downloads += 1; });
  // the button stays focusable (aria-disabled) and explains itself when it is used
  await button.focus();
  await page.keyboard.press('Enter');
  const dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('Export HDL: the system has errors');
  await expect(dialog).toContainText('must be served');
  await dialog.getByRole('button', { name: 'Close' }).click();
  expect(downloads).toBe(0);
});
