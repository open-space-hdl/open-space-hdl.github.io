// Browser tests of a system with subsystems (format version 2): it opens, shows its subsystems as blocks, saves byte
// for byte and exports one entity and one scoped constraint file per subsystem.
import { test } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { unzipStore } from '../../assets/composer/js/model/zip.js';
import { expect, open, watch } from './helpers.mjs';

const fixture = readFileSync(new URL('../fixtures/subsystems/dual_rmap_node.composer.json', import.meta.url));
const golden = (/** @type {string} */ name) => readFileSync(new URL(`../golden/subsystems/${name}`, import.meta.url), 'utf-8');
const stable = (/** @type {string} */ t) => t
  .replace(/Generated by .* from (\S+)/, 'Generated from $1')
  .replace(/(SHA-256 of \S+: )[0-9a-f]{64}/, '$1*')
  .replace(/(Block catalog: )[0-9a-f]+/, '$1*');

/** @type {string[]} */
let problems = [];

test.beforeEach(async ({ page }) => {
  problems = [];
  watch(page, problems);
});

test.afterEach(() => {
  expect(problems, problems.join('\n')).toEqual([]);
});

test('a system with subsystems opens, saves unchanged and exports every subsystem', async ({ page }) => {
  await open(page);
  await page.locator('input[type="file"]').setInputFiles({ name: 'dual_rmap_node.composer.json', mimeType: 'application/json', buffer: fixture });
  await expect(page.locator('.cmp-block')).toHaveCount(2);
  await expect(page.locator('[data-block="rmap_node0"]')).toContainText('rmap_node');
  // no errors: the export is ready
  const button = page.getByRole('button', { name: 'Export HDL', exact: true });
  await expect(button).toHaveAttribute('aria-disabled', 'false');
  // saved, the file is the same byte for byte
  const [saved] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Save', exact: true }).click()]);
  expect(readFileSync(await saved.path(), 'utf-8')).toBe(fixture.toString('utf-8'));
  // the export: the top level, then every subsystem with its scoped constraints
  const [download] = await Promise.all([page.waitForEvent('download'), button.click()]);
  const files = unzipStore(new Uint8Array(readFileSync(await download.path())));
  expect(files.map((f) => f.name)).toEqual([
    'dual_rmap_node.vhd', 'dual_rmap_node_compile_order.txt', 'dual_rmap_node.xdc', 'dual_rmap_node_top.xdc',
    'dual_rmap_node_address_map.md', 'dual_rmap_node_regs.h',
    'spw_port.vhd', 'spw_port.xdc', 'rmap_node.vhd', 'rmap_node.xdc', 'dual_rmap_node.composer.json',
  ]);
  for (const f of files.slice(0, -1)) expect(stable(new TextDecoder().decode(f.data)), f.name).toBe(stable(golden(f.name)));
});
