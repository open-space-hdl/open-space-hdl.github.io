// The VHDL export (model/hdl.js and tools/composer_hdl.mjs): deterministic files with the generator header, the top
// level written from the resolved netlist and nothing else, the compile order in its line format, the two constraint
// files, the differences between two netlists, and the command line tool with its exit status.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Catalog } from '../../assets/composer/js/model/catalog.js';
import { COMPILE_ORDER_FORMAT, exportHdl, LINE_LENGTH, netlistDiff } from '../../assets/composer/js/model/hdl.js';
import { netlist } from '../../assets/composer/js/model/netlist.js';
import { resolve } from '../../assets/composer/js/model/resolver.js';
import { fromText } from '../../assets/composer/js/model/serialize.js';
import { loadCatalogJson, ROOT } from './helpers.mjs';

/** The catalog with a file list for every source that has none yet (two files per repository). */
function catalogJsonWithFiles() {
  const json = loadCatalogJson();
  for (const s of json.sources) if (!s.files) s.files = [`src/${s.id}_pkg.vhd`, `src/${s.id}_top.vhd`];
  return json;
}
const cat = new Catalog(catalogJsonWithFiles());
const EXAMPLES = `${ROOT}assets/composer/examples/`;
const examples = readdirSync(EXAMPLES).filter((f) => f.endsWith('.composer.json'));
const INFO = { generator: 'Open Space Composer test', input: 'x.composer.json', sha256: 'ab'.repeat(32) };

/** @param {string} file */
function exported(file) {
  const { design } = fromText(readFileSync(EXAMPLES + file, 'utf-8'), cat);
  const resolved = /** @type {any} */ (netlist(cat, design, resolve(cat, design)));
  const out = exportHdl(cat, resolved, { ...INFO, description: design.description, connections: design.connections });
  return { design, resolved, ...out, byName: Object.fromEntries(out.files.map((f) => [f.name, f.text])) };
}

test('every example exports four complete files, the same twice, with the generator header', () => {
  assert.ok(examples.length >= 5);
  for (const f of examples) {
    const a = exported(f);
    const e = a.resolved.entity;
    assert.deepEqual(a.problems, [], f);
    assert.deepEqual(a.files.map((x) => x.name), [`${e}.vhd`, `${e}_compile_order.txt`, `${e}.xdc`, `${e}_top.xdc`]);
    assert.deepEqual(exported(f).files, a.files, `${f}: not deterministic`);
    for (const { name, text } of a.files) {
      assert.ok(text.endsWith('\n') && !text.endsWith('\n\n'), `${name}: one final newline`);
      assert.ok(text.includes('Generated by Open Space Composer test from x.composer.json'), `${name}: generator`);
      assert.ok(text.includes(`SHA-256 of x.composer.json: ${'ab'.repeat(32)}`), `${name}: input hash`);
      assert.ok(text.includes(`Block catalog: ${cat.id}`), `${name}: catalog`);
      assert.ok(text.includes('Do not edit this file'), `${name}: do not edit`);
      text.split('\n').forEach((line, k) => {
        // the source and file lines of the compile order are data for tools, one entry per line
        const data = name.endsWith('_compile_order.txt') && /^(source|file) /.test(line);
        assert.ok(data || line.length <= LINE_LENGTH, `${name}:${k + 1} is longer than ${LINE_LENGTH} characters`);
        assert.ok(!/\s$/.test(line) && !line.includes('\t'), `${name}:${k + 1}: trailing white space or tab`);
        assert.ok(!line.includes(String.fromCharCode(0x2014)), `${name}:${k + 1}: em-dash`);
      });
    }
  }
});

test('the top level holds every port, signal, instance and assignment of the netlist', () => {
  for (const f of examples) {
    const { resolved: r, byName } = exported(f);
    const vhd = byName[`${r.entity}.vhd`];
    assert.match(vhd, new RegExp(`^entity ${r.entity} is$`, 'm'));
    assert.match(vhd, new RegExp(`^architecture rtl of ${r.entity} is$`, 'm'));
    for (const c of r.context) assert.ok(vhd.includes(c), `${f}: ${c}`);
    for (const p of r.ports) assert.match(vhd, new RegExp(`^        ${p.name} +: ${p.dir} +${p.type.replace(/[()]/g, '\\$&')};?$`, 'm'), `${f}: port ${p.name}`);
    for (const s of r.signals) {
      const decl = vhd.match(new RegExp(`^    signal ${s.name} +: `, 'gm')) ?? [];
      assert.equal(decl.length, 1, `${f}: signal ${s.name}`);
    }
    for (const inst of r.instances) {
      assert.match(vhd, new RegExp(`^    i_${inst.id} : entity ${inst.library}\\.${inst.entity}$`, 'm'), `${f}: ${inst.id}`);
      // the generic map of this instance: every generic, the defaults marked
      const from = vhd.indexOf(`    i_${inst.id} : entity `);
      const map = vhd.slice(from, vhd.indexOf('        port map (', from)).split('\n');
      for (const g of inst.generics) {
        const line = map.find((l) => new RegExp(`^ {12}${g.name} +=> `).test(l) && l.includes(g.vhdl));
        assert.ok(line, `${f}: ${inst.id}.${g.name}`);
        assert.equal(/-- default$/.test(/** @type {string} */ (line)), g.default, `${f}: ${inst.id}.${g.name} default mark`);
      }
      for (const p of inst.ports) {
        const mapped = new RegExp(`^ {12}${p.name} +=> ${String(p.actual).replace(/[()]/g, '\\$&')},?$`, 'm').test(vhd);
        assert.equal(mapped, !p.useDefault, `${f}: ${inst.id}.${p.name}`);
      }
    }
    for (const n of r.nets) {
      const to = n.to.replace(/[()]/g, '\\$&');
      assert.match(vhd, new RegExp(`^    ${to} +<= `, 'm'), `${f}: assignment to ${n.to}`);
    }
    assert.equal((vhd.match(/ <= /g) ?? []).length, r.nets.length, `${f}: one assignment per net`);
  }
});

test('the compile order names every source at its commit and lists the files library by library, the top level last', () => {
  for (const f of examples) {
    const { resolved: r, byName } = exported(f);
    const lines = byName[`${r.entity}_compile_order.txt`].split('\n');
    assert.equal(lines[0], COMPILE_ORDER_FORMAT);
    const sources = lines.filter((l) => l.startsWith('source '));
    const files = lines.filter((l) => l.startsWith('file '));
    assert.equal(sources.length, r.compile.length);
    r.compile.forEach((/** @type {any} */ c, k) => {
      const repo = cat.sourceById.get(c.source).repo;
      assert.ok(sources[k].startsWith(`source ${repo} ${c.url} ${c.commit}`), `${f}: ${sources[k]}`);
      assert.equal(sources[k].endsWith(' recursive'), Boolean(cat.sourceById.get(c.source).submodules));
    });
    // libraries in the order of resolved.compile, every file of a library together
    const libs = files.map((l) => l.split(' ')[1]);
    assert.deepEqual([...new Set(libs)], [...r.compile.map((/** @type {any} */ c) => c.library), r.entity]);
    assert.equal(files.at(-1), `file ${r.entity} ${r.entity}.vhd`);
    for (const l of files.slice(0, -1)) assert.match(l, /^file \w+ [\w.-]+\/\S+\.vhdl?$/, `${f}: ${l}`);
  }
  // a vendor-specific block outside the file list of its repository is added with its notes
  const { byName } = exported('spacefibre_node.composer.json');
  const order = byName['spacefibre_node_compile_order.txt'];
  assert.match(order, /^file openfibre openfibre\/hdl\/ofb_pa_gty\/src\/ofb_pa_gty\.vhd$/m);
  assert.match(order, /^# - ofb_pa_gty: Vendor-specific \(AMD Versal GTY\)/m);
  assert.match(order, /olo_base_constraints_amd\.tcl/);
});

test('the scoped constraints hold the exceptions, the top-level file the clocks and the I/O registers', () => {
  for (const f of examples) {
    const { resolved: r, byName } = exported(f);
    const scoped = byName[`${r.entity}.xdc`];
    const top = byName[`${r.entity}_top.xdc`];
    assert.match(scoped, new RegExp(`read_xdc -ref ${r.entity} ${r.entity}\\.xdc`));
    assert.ok(!/^create_clock|^set_property IOB/m.test(scoped), `${f}: the scoped file holds only exceptions`);
    const maxDelays = r.constraints.filter((/** @type {any} */ c) => c.kind === 'max_delay');
    assert.equal((scoped.match(/^set_max_delay -datapath_only -from \$clk_\w+ -to \$clk_\w+ \d+\.\d{3}$/gm) ?? []).length, maxDelays.length, f);
    for (const c of r.constraints.filter((/** @type {any} */ x) => x.kind === 'false_path')) {
      assert.ok(scoped.includes(`set_false_path -from [get_ports ${c.from.length > 1 ? `{${c.from.join(' ')}}` : c.from[0]}]`), `${f}: false path`);
    }
    for (const c of r.clocks.filter((/** @type {any} */ x) => x.source === 'top')) {
      assert.ok(top.includes(`create_clock -period ${(1e9 / c.frequencyHz).toFixed(3)} -name ${c.actual} [get_ports ${c.actual}]`), `${f}: ${c.actual}`);
    }
    const io = r.constraints.filter((/** @type {any} */ x) => x.kind === 'io_register');
    assert.equal((top.match(/^set_property IOB TRUE /gm) ?? []).length, io.length, f);
    for (const c of io) assert.ok(scoped.includes(c.ports.join(', ')), `${f}: the scoped file names the ports that need I/O registers`);
  }
  // a clock of a block is found at the pin of its instance
  const { byName } = exported('spacefibre_node.composer.json');
  assert.match(byName['spacefibre_node.xdc'], /^set clk_lane \[get_clocks -of_objects \[get_pins i_pa0\/LaneClk\]\]$/m);
});

test('a source without file list at the pinned commit makes the export incomplete', () => {
  const json = loadCatalogJson();
  for (const s of json.sources) if (s.id !== 'olo') delete s.files;
  const c = new Catalog(json);
  const { design } = fromText(readFileSync(`${EXAMPLES}spw_rmap_node.composer.json`, 'utf-8'), c);
  const { problems } = exportHdl(c, /** @type {any} */ (netlist(c, design, resolve(c, design))), INFO);
  assert.equal(problems.length, 2);
  assert.match(problems[0], /^openwire at [0-9a-f]{10}: no compile_order\.txt at this pin; the export of a system with openwire needs a pin of the catalog/);
});

test('the differences of two netlists name what changes, nothing for equal ones', () => {
  const text = readFileSync(`${ROOT}tests/fixtures/invalid/spfi_encrypt_release_4128.composer.json`, 'utf-8');
  const stored = JSON.parse(text).resolved;
  assert.deepEqual(netlistDiff(stored, stored), []);
  const { design } = fromText(text, cat);
  const diff = netlistDiff(stored, /** @type {any} */ (netlist(cat, design, resolve(cat, design))));
  assert.ok(diff.includes("Assignment to rmap0_M_Axi_RLast_s: '0' becomes '1'."), diff.join('\n'));
  assert.ok(diff.includes("Assignment to edac0_In_Valid_s(7): '0' becomes '1'."));
  assert.ok(diff.includes('Generic rmap0.WinInit_g: WinInitOpen_c becomes openrmap.omap_pkg.WinInitOpen_c.'));
});

test('the command line tool refuses a changed netlist, exports with --resolve and checks the sources it reads', () => {
  const dir = mkdtempSync(join(tmpdir(), 'composer-hdl-'));
  try {
    const catFile = join(dir, 'catalog.json');
    writeFileSync(catFile, JSON.stringify(catalogJsonWithFiles()));
    const run = (/** @type {string[]} */ args) => spawnSync(process.execPath, [`${ROOT}tools/composer_hdl.mjs`, ...args, '--catalog', catFile], { encoding: 'utf-8' });
    // a file of an older catalog: the differences, and with --resolve the errors of the new resolution
    const invalid = `${ROOT}tests/fixtures/invalid/spfi_encrypt_release_4128.composer.json`;
    const refused = run([invalid, join(dir, 'a')]);
    assert.equal(refused.status, 1, refused.stderr);
    assert.match(refused.stdout, /resolves differently/);
    assert.match(refused.stdout, /rmap0_M_Axi_RLast_s: '0' becomes '1'/);
    const errors = run([invalid, join(dir, 'b'), '--resolve']);
    assert.equal(errors.status, 2, errors.stdout);
    assert.match(errors.stderr, /the system has errors; nothing exported/);
    assert.match(errors.stderr, /ocr0: ReleaseBytes_g = 4128 must be a power of two/);
    assert.throws(() => readdirSync(join(dir, 'b')), 'nothing written');
    // the system of the user: its RMAP target on the AXI4-Lite decoder (AxiMaxBeats_g = 1) hits a known defect of the
    // pinned OpenRMAP, so the export is refused. Once the fix is pinned, this fixture becomes a positive export test
    // with the GHDL check and the run to 0 ns, like the examples in the continuous integration.
    const user = run([`${ROOT}tests/fixtures/spfi_encrypt.composer.json`, join(dir, 'e'), '--resolve']);
    assert.equal(user.status, 2, user.stdout);
    assert.match(user.stderr, /rmap0: Known defect: commands longer than one AXI transaction return or write wrong data with AxiMaxBeats_g < 4; fix in progress in OpenRMAP\./);
    assert.throws(() => readdirSync(join(dir, 'e')), 'nothing written');
    // an example of the current catalog exports without --resolve, with the input file and its hash in the header
    const example = run([`${EXAMPLES}spw_rmap_node.composer.json`, join(dir, 'c')]);
    assert.equal(example.status, 0, example.stderr);
    assert.deepEqual(readdirSync(join(dir, 'c')).sort(), ['spw_rmap_node.vhd', 'spw_rmap_node.xdc', 'spw_rmap_node_compile_order.txt', 'spw_rmap_node_top.xdc']);
    assert.match(readFileSync(join(dir, 'c', 'spw_rmap_node.vhd'), 'utf-8'), /SHA-256 of spw_rmap_node\.composer\.json: [0-9a-f]{64}/);
    // a sources root without checkouts is an error
    const noSources = run([`${EXAMPLES}spw_rmap_node.composer.json`, join(dir, 'd'), '--sources', join(dir, 'none')]);
    assert.equal(noSources.status, 2);
    assert.match(noSources.stderr, /open-logic-ft: no checkout at/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test('the VHDL export of every example with the published catalog matches its golden files', () => {
  // the header names the generator, the hash of the example file and the catalog, which change with every catalog
  const stable = (/** @type {string} */ t) => t
    .replace(/Generated by .* from (\S+)/, 'Generated from $1')
    .replace(/(SHA-256 of \S+: )[0-9a-f]{64}/, '$1*')
    .replace(/(Block catalog: )[0-9a-f]+/, '$1*');
  const real = new Catalog(loadCatalogJson());
  for (const f of examples) {
    const text = readFileSync(EXAMPLES + f, 'utf-8');
    const { design } = fromText(text, real);
    const resolved = /** @type {any} */ (netlist(real, design, resolve(real, design)));
    const { files, problems } = exportHdl(real, resolved, { ...INFO, input: f, description: design.description, connections: design.connections });
    assert.deepEqual(problems, [], `${f}: the catalog lacks file lists`);
    for (const { name, text: got } of files) {
      const want = readFileSync(`${ROOT}tests/golden/${name}`, 'utf-8');
      assert.equal(stable(got), stable(want), `${name} differs from its golden file (run node tools/composer_examples.mjs)`);
    }
  }
});
