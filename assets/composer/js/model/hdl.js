// @ts-check
/**
 * VHDL export of a system (pure, deterministic, no DOM): the files a build of the system needs, written from its
 * resolved netlist. Used by the button Export HDL of the Composer and by tools/composer_hdl.mjs.
 *
 *   <system>.vhd                 the top level: the instances, signals and assignments of the netlist, nothing else
 *   <system>_compile_order.txt   the source repositories at their pinned commits and every file in compile order
 *   <system>.xdc                 timing exceptions of the system, for read_xdc -ref <system>: valid on its own and
 *                                inside a larger design
 *   <system>_top.xdc             what applies only when the system is the top level of the FPGA: the clocks of its
 *                                clock ports and the I/O registers
 *
 * A system with subsystems also gets, for every definition it uses (resolved.subsystems):
 *
 *   <subsystem>.vhd              its entity, in the library of the top level, written as a top level is
 *   <subsystem>.xdc              its timing exceptions, for read_xdc -ref <subsystem>
 *
 * The same netlist and the same input give the same text, byte by byte.
 */

/** @typedef {import('./catalog.js').Catalog} Catalog */
/** @typedef {import('./netlist.js').ResolvedNetlist} ResolvedNetlist */
/** @typedef {import('./netlist.js').Net} Net */

/** Maximum length of a generated line. */
export const LINE_LENGTH = 120;
/** First line of a compile order file. */
export const COMPILE_ORDER_FORMAT = 'format composer-compile-order 1';

const RULE = '-'.repeat(99);
const INNER_RULE = `    ${'-'.repeat(95)}`;

/**
 * @typedef {object} ExportInfo
 * @property {string} generator    name and version of the generator, for example "Open Space Composer 0.4.0-beta"
 * @property {string} input        file name of the system file the export is made from
 * @property {string} sha256       SHA-256 of that file, hexadecimal
 * @property {string} [description]   description of the system
 * @property {{ id: string, from: string, to: string }[]} [connections]   connections of the system (for the comments)
 * @property {Record<string, { files: string[], submodules?: boolean }>} [fileLists]   file lists of sources read from
 *           local checkouts (source id -> files in compile order), instead of the lists of the catalog
 * @property {Record<string, { description?: string, connections?: { id: string, from: string, to: string }[] }>} [subsystems]
 *           description and connections of every subsystem definition (for the comments)
 */

/**
 * @typedef {object} HdlFile
 * @property {string} name
 * @property {string} text
 */

/**
 * Words of a text in lines of at most width characters (a longer word stays on its own line).
 * @param {string} text
 * @param {number} width
 */
export function wrap(text, width) {
  /** @type {string[]} */
  const lines = [];
  let line = '';
  for (const word of text.split(/\s+/).filter(Boolean)) {
    if (line && line.length + 1 + word.length > width) {
      lines.push(line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(line);
  return lines;
}

/**
 * Comment lines of a text.
 * @param {string} lead   comment start with its indentation, for example "    --" or "#"
 * @param {string} text
 */
function comment(lead, text) {
  return wrap(text, LINE_LENGTH - lead.length - 1).map((l) => `${lead} ${l}`);
}

/**
 * Lines of the generator header (without comment characters).
 * @param {ResolvedNetlist} resolved
 * @param {ExportInfo} info
 */
function headerLines(resolved, info) {
  return [
    `Generated by ${info.generator} from ${info.input}`,
    `SHA-256 of ${info.input}: ${info.sha256}`,
    `Block catalog: ${resolved.catalog}`,
    'Do not edit this file: change the system in the Composer and export it again.',
  ];
}

/**
 * Pads the first column of rows to a common width.
 * @param {[string, string][]} rows
 * @param {string} sep
 */
function align(rows, sep) {
  const w = Math.max(0, ...rows.map(([a]) => a.length));
  return rows.map(([a, b]) => `${a.padEnd(w)}${sep}${b}`);
}

/**
 * A VHDL bit-string literal that fits into a line: binary as resolved writes it, hexadecimal when it is long.
 * @param {string} literal
 */
function shortLiteral(literal) {
  const m = /^"([01]+)"$/.exec(literal);
  if (!m || m[1].length <= 32) return literal;
  const bits = m[1];
  const digits = Math.ceil(bits.length / 4);
  const padded = bits.padStart(digits * 4, '0');
  let hex = '';
  for (let k = 0; k < digits; k += 1) hex += Number.parseInt(padded.slice(4 * k, 4 * k + 4), 2).toString(16).toUpperCase();
  return bits.length % 4 === 0 ? `x"${hex}"` : `${bits.length}x"${hex}"`;
}

/**
 * The library clause of the context: a "use" line indented below its library, a blank line between libraries.
 * @param {string[]} context
 */
function contextLines(context) {
  /** @type {string[]} */
  const out = [];
  for (const line of context) {
    if (line.startsWith('library ')) {
      if (out.length) out.push('');
      out.push(line);
    } else out.push(`    ${line}`);
  }
  return out;
}

/**
 * Text of an instance for the comments: placed, or inserted and why.
 * @param {Catalog} cat
 * @param {Record<string, any>} inst
 */
function instanceTitle(cat, inst) {
  if (String(inst.block).startsWith('subsystem/')) return `${inst.id}: subsystem ${inst.entity}`;
  const name = cat.blocks.get(inst.block)?.name;
  const what = `${inst.entity} (${inst.library}${name ? `, ${name}` : ''})`;
  return inst.origin === 'user' ? `${inst.id}: ${what}` : `${inst.id}: ${what}, inserted by the Composer: ${inst.reason ?? inst.role}`;
}

/**
 * The top level, or the entity of a subsystem.
 * @param {Catalog} cat
 * @param {ResolvedNetlist} resolved
 * @param {ExportInfo} info   for a subsystem: description and connections of the definition
 * @param {string} [parent]   for a subsystem: the system it belongs to
 */
function topLevel(cat, resolved, info, parent) {
  const entity = resolved.entity;
  const title = parent ? `-- ${entity}: subsystem of ${parent}` : `-- ${entity}: top level of the system`;
  /** @type {string[]} */
  const out = [RULE, title, '--', ...headerLines(resolved, info).map((l) => `-- ${l}`), RULE];
  if (info.description) out.push('', RULE, '-- Description', RULE, ...comment('--', info.description));
  out.push('', RULE, '-- Libraries', RULE, ...contextLines(resolved.context));

  // entity: the ports in the order of the netlist, a comment above every group (reset, clocks, each interface)
  out.push('', RULE, '-- Entity', RULE, `entity ${entity} is`);
  if (resolved.ports.length) {
    const w = Math.max(...resolved.ports.map((p) => p.name.length));
    out.push('    port (');
    let group = '';
    resolved.ports.forEach((p, k) => {
      const g = p.kind === 'interface' ? `${p.interface}${p.domain ? `, clock domain ${p.domain}` : ''}` : p.kind === 'clock' ? 'Clocks' : 'Reset';
      if (g !== group) {
        if (group) out.push('');
        out.push(`        -- ${g}`);
        group = g;
      }
      out.push(`        ${p.name.padEnd(w)} : ${p.dir.padEnd(5)} ${p.type}${k < resolved.ports.length - 1 ? ';' : ''}`);
    });
    out.push('    );');
  }
  out.push('end entity;');

  // signals: one block per instance, in the order of its ports
  /** @type {Map<string, string>} */
  const owner = new Map();
  for (const inst of resolved.instances) for (const p of inst.ports) if (typeof p.actual === 'string') owner.set(p.actual, inst.id);
  out.push('', RULE, '-- Architecture', RULE, `architecture rtl of ${entity} is`);
  /** @type {Map<string, { name: string, type: string }[]>} */
  const blocks = new Map(resolved.instances.map((i) => [i.id, []]));
  /** @type {{ name: string, type: string }[]} */
  const other = [];
  for (const s of resolved.signals) {
    const id = owner.get(s.name);
    (id && blocks.get(id) ? /** @type {{ name: string, type: string }[]} */ (blocks.get(id)) : other).push(s);
  }
  for (const inst of resolved.instances) {
    const sigs = /** @type {{ name: string, type: string }[]} */ (blocks.get(inst.id));
    if (!sigs.length) continue;
    out.push('', ...comment('    --', instanceTitle(cat, inst)));
    out.push(...align(sigs.map((s) => [`    signal ${s.name}`, s.type]), ' : ').map((l) => `${l};`));
  }
  if (other.length) {
    out.push('', '    -- Other signals');
    out.push(...align(other.map((s) => [`    signal ${s.name}`, s.type]), ' : ').map((l) => `${l};`));
  }
  out.push('', 'begin');

  // instances
  out.push('', INNER_RULE, '    -- Instances', INNER_RULE);
  resolved.instances.forEach((inst, k) => {
    if (k > 0) out.push('');
    out.push(...comment('    --', instanceTitle(cat, inst)), `    i_${inst.id} : entity ${inst.library}.${inst.entity}`);
    if (inst.generics.length) {
      // every generic explicitly, so that a new default of a core never changes the system silently; the defaults
      // are marked in a column of their own
      const gens = /** @type {{ name: string, vhdl: string, default: boolean }[]} */ (inst.generics);
      const w = Math.max(...gens.map((g) => g.name.length));
      const rows = gens.map((g, j) => `            ${g.name.padEnd(w)} => ${g.vhdl}${j < gens.length - 1 ? ',' : ''}`);
      const wr = Math.max(...rows.map((r) => r.length));
      out.push('        generic map (');
      rows.forEach((r, j) => out.push(gens[j].default ? `${r.padEnd(wr)} -- default` : r));
      out.push('        )');
    }
    // ports with useDefault keep their VHDL default
    const ports = inst.ports.filter((/** @type {{ useDefault?: boolean }} */ p) => !p.useDefault);
    const w = Math.max(...ports.map((/** @type {{ name: string }} */ p) => p.name.length));
    out.push('        port map (');
    ports.forEach((/** @type {{ name: string, actual: string }} */ p, j) => {
      out.push(`            ${p.name.padEnd(w)} => ${p.actual}${j < ports.length - 1 ? ',' : ''}`);
    });
    out.push('        );');
  });

  // assignments: the connections, the tie-offs and the top-level ports, each group with what it is for
  const connText = new Map((info.connections ?? []).map((c) => [c.id, `${c.from} to ${c.to}`]));
  const portItf = new Map(resolved.ports.map((p) => [p.name, p.kind === 'interface' ? p.interface : p.name]));
  /** @type {Map<string, { title: string, nets: Net[] }>} */
  const groups = new Map();
  for (const n of resolved.nets) {
    /** @type {string} */
    let key;
    /** @type {string} */
    let title;
    if (n.kind === 'connection') {
      key = `c:${n.connection}`;
      title = `Connection ${n.connection}${connText.has(n.connection ?? '') ? `: ${connText.get(n.connection ?? '')}` : ''}`;
    } else if (n.kind === 'constant') {
      key = `k:${n.connection}`;
      title = `Side band constants of connection ${n.connection}: ${(n.fields ?? []).map((f) => `${f.label} ${typeof f.value === 'number' && f.bits > 4 ? `${f.value} (0x${f.value.toString(16).toUpperCase()})` : String(f.value)}`).join(', ')}`;
    } else if (n.kind === 'tie-off') {
      key = `t:${n.reason ?? n.to}`;
      title = n.reason ?? 'Tie-off';
    } else {
      const itf = portItf.get(portItf.has(n.to) ? n.to : n.from) ?? 'Top-level port';
      key = `p:${itf}`;
      title = `Top-level ports of ${itf}`;
    }
    const g = groups.get(key) ?? { title, nets: [] };
    g.nets.push(n);
    groups.set(key, g);
  }
  // a connection is followed by its constants
  const sections = /** @type {[string, (key: string) => boolean][]} */ ([
    ['Connections', (key) => key.startsWith('c:') || key.startsWith('k:')],
    ['Tie-offs', (key) => key.startsWith('t:')],
    ['Top-level ports', (key) => key.startsWith('p:')],
  ]);
  const keys = [...groups.keys()];
  const ordered = keys
    .filter((key) => key.startsWith('c:'))
    .flatMap((key) => [key, ...(groups.has(`k:${key.slice(2)}`) ? [`k:${key.slice(2)}`] : [])]);
  const rest = keys.filter((key) => !ordered.includes(key));
  const all = [...ordered, ...rest];
  for (const [name, test] of sections) {
    const mine = all.filter(test);
    if (!mine.length) continue;
    out.push('', INNER_RULE, `    -- ${name}`, INNER_RULE);
    for (const key of mine) {
      const g = /** @type {{ title: string, nets: Net[] }} */ (groups.get(key));
      out.push(...comment('    --', g.title));
      out.push(...align(g.nets.map((n) => [`    ${n.to}`, `${shortLiteral(n.from)};`]), ' <= '));
      out.push('');
    }
    out.pop();
  }
  out.push('', 'end architecture;', '');
  return out.join('\n');
}

/**
 * Directory of a source in the sources root: its repository name.
 * @param {Catalog} cat
 * @param {Record<string, any>} c   entry of resolved.compile
 */
function sourceDir(cat, c) {
  return cat.sourceById.get(c.source)?.repo ?? c.source;
}

/**
 * The compile order.
 * @param {Catalog} cat
 * @param {ResolvedNetlist} resolved
 * @param {ExportInfo} info
 * @param {string[]} problems
 */
function compileOrder(cat, resolved, info, problems) {
  const entity = resolved.entity;
  // file list of every source: from local checkouts where the caller read them, else from the catalog at its pin
  const lists = resolved.compile.map((c) => {
    const given = info.fileLists?.[c.source];
    if (given) return given;
    const src = cat.sourceById.get(c.source);
    return src && src.commit === c.commit && Array.isArray(src.files) ? { files: /** @type {string[]} */ (src.files), submodules: Boolean(src.submodules) } : undefined;
  });
  /** @type {string[]} */
  const out = [COMPILE_ORDER_FORMAT, ...headerLines(resolved, info).map((l) => `# ${l}`), '#'];
  out.push(
    ...comment('#', `Compile order of ${entity}. Each "source" line names a repository: clone it into the directory of that name in a sources root and check out the commit ("recursive": with its submodules). Each "file" line names a VHDL-2008 file and its library, in compile order: the sources relative to the sources root, the top level relative to this file. Only synthesis sources are listed.`),
    '',
  );
  resolved.compile.forEach((c, k) => {
    out.push(`source ${sourceDir(cat, c)} ${c.url} ${c.commit}${c.tag ? ` tag ${c.tag}` : ''}${lists[k]?.submodules ? ' recursive' : ''}`);
  });
  out.push('');
  /** @type {string[]} */
  const notes = [];
  /** @type {string[]} */
  const blockNotes = [];
  resolved.compile.forEach((c, k) => {
    const dir = sourceDir(cat, c);
    if (c.note) notes.push(`${dir}: ${c.note}`);
    const list = lists[k];
    if (!list) {
      const pin = cat.sourceById.get(c.source)?.commit;
      problems.push(pin === c.commit
        ? `${dir} at ${String(c.commit).slice(0, 10)}: no compile_order.txt at this pin; the export of a system with ${dir} needs a pin of the catalog with this file list.`
        : `${dir} at ${String(c.commit).slice(0, 10)}: no compile_order.txt at this pin; save the system again with the current catalog of the Composer.`);
      return;
    }
    for (const f of list.files) out.push(`file ${c.library} ${dir}/${f}`);
    // blocks whose file is not part of the file list of the repository (vendor-specific adapters)
    const extra = new Map();
    for (const inst of [...resolved.instances, ...(resolved.subsystems ?? []).flatMap((s) => s.netlist.instances)]) {
      const b = cat.blocks.get(inst.block);
      if (b && b.source === c.source && !list.files.includes(b.path) && !extra.has(b.path)) extra.set(b.path, b);
    }
    for (const [path, b] of extra) {
      out.push(`file ${c.library} ${dir}/${path}`);
      for (const n of b.notes ?? []) blockNotes.push(`${b.entity}: ${n}`);
    }
  });
  // the subsystems in the library of the top level, leaves first, then the top level
  for (const s of resolved.subsystems ?? []) out.push(`file ${entity} ${s.name}.vhd`);
  out.push(`file ${entity} ${entity}.vhd`);
  const olo = resolved.compile.find((c) => c.source === 'olo');
  /** @type {Set<string>} */
  const scripts = new Set();
  for (const con of [...resolved.constraints, ...(resolved.subsystems ?? []).flatMap((s) => s.netlist.constraints)]) {
    if (con.kind !== 'vendor_scoped' || scripts.has(con.file)) continue;
    scripts.add(con.file);
    blockNotes.push(`${olo ? `${sourceDir(cat, olo)}: ` : ''}${con.note} File ${con.file}.`);
  }
  if (resolved.subsystems?.length) {
    const names = resolved.subsystems.map((s) => s.name);
    blockNotes.push(`Subsystems: ${names.join(', ')}. Each has its timing exceptions in a file of its own, read scoped to its entity: ${names.map((n) => `read_xdc -ref ${n} ${n}.xdc`).join('; ')}.`);
  }
  notes.push(...blockNotes);
  if (notes.length) {
    out.push('', '# Notes');
    for (const n of notes) out.push(...wrap(n, LINE_LENGTH - 4).map((l, k) => `${k ? '#   ' : '# - '}${l}`));
  }
  out.push('');
  return out.join('\n');
}

/**
 * Tcl expression of a clock of the netlist (a top-level clock port or the clock output of an instance).
 * @param {string} ref   port name or "<instance>.<port>"
 */
function clockObject(ref) {
  const dot = ref.indexOf('.');
  return dot < 0 ? `[get_ports ${ref}]` : `[get_pins i_${ref.slice(0, dot)}/${ref.slice(dot + 1)}]`;
}

/**
 * Tcl list of port names.
 * @param {string[]} ports
 */
function portList(ports) {
  return ports.length === 1 ? `[get_ports ${ports[0]}]` : `[get_ports {${ports.join(' ')}}]`;
}

/**
 * The timing exceptions, scoped to the entity of the system or of a subsystem.
 * @param {ResolvedNetlist} resolved
 * @param {ExportInfo} info
 * @param {string} [parent]   for a subsystem: the system it belongs to
 */
function exceptions(resolved, info, parent) {
  const entity = resolved.entity;
  /** @type {string[]} */
  const out = [...headerLines(resolved, info).map((l) => `# ${l}`), '#'];
  out.push(
    ...comment('#', parent
      ? `Timing exceptions of the subsystem ${entity} of ${parent}, in terms of its ports and instances. Read the file scoped to the entity: read_xdc -ref ${entity} ${entity}.xdc (in a project: set_property SCOPED_TO_REF ${entity} [get_files ${entity}.xdc]). The clocks come from ${parent}.`
      : `Timing exceptions of ${entity}, in terms of its ports and instances. Read the file scoped to the entity, alone or with the system inside a larger design: read_xdc -ref ${entity} ${entity}.xdc (in a project: set_property SCOPED_TO_REF ${entity} [get_files ${entity}.xdc]). The clocks come from the design around the system, or from ${entity}_top.xdc when the system is the top level.`),
  );
  if (!parent && resolved.subsystems?.length) {
    out.push('#', ...comment('#', `The subsystems have their own files, read scoped to their entities as well: ${resolved.subsystems.map((s) => `${s.name}.xdc`).join(', ')}.`));
  }
  const io = resolved.constraints.filter((c) => c.kind === 'io_register');
  if (io.length) {
    const ports = io.flatMap((c) => c.ports).join(', ');
    out.push('#', ...comment('#', parent
      ? `I/O registers: the output flip-flops of ${ports} belong in the I/O blocks at the pins of the top level; ${parent}_top.xdc places them when ${parent} is the top level.`
      : `I/O registers: when the system is not the top level, place the output flip-flops of ${ports} in the I/O blocks at the pins of the top level (${entity}_top.xdc does it when the system is the top level).`));
  }
  // one variable per clock that a constraint refers to
  /** @type {Map<string, string>} */
  const vars = new Map();
  const clockVar = (/** @type {string} */ ref) => {
    if (!vars.has(ref)) {
      const clk = resolved.clocks.find((c) => (c.source === 'top' ? c.actual === ref : c.source === ref));
      const base = `clk_${(clk?.id ?? ref).replace(/\W/g, '_')}`;
      let name = base;
      for (let k = 2; [...vars.values()].includes(name); k += 1) name = `${base}_${k}`;
      vars.set(ref, name);
    }
    return `$${vars.get(ref)}`;
  };
  /** @type {string[]} */
  const body = [];
  for (const c of resolved.constraints) {
    if (c.kind === 'max_delay') {
      body.push('', ...comment('#', c.note), `set_max_delay${c.datapathOnly ? ' -datapath_only' : ''} -from ${clockVar(c.from)} -to ${clockVar(c.to)} ${Number(c.ns).toFixed(3)}`);
    } else if (c.kind === 'false_path') {
      body.push('', ...comment('#', c.note), `set_false_path -from ${portList(c.from)}`);
    } else if (c.kind === 'vendor_scoped' && !parent) {
      // once, in the file of the system
      body.push('', ...comment('#', `${c.note} The script ${c.file} is part of the Open Logic sources; add it to the project once (see the compile order).`));
    }
  }
  if (vars.size) {
    out.push('', '# Clocks', ...align([...vars].map(([ref, v]) => [`set ${v}`, `[get_clocks -of_objects ${clockObject(ref)}]`]), ' '));
  }
  out.push(...body, '');
  return out.join('\n');
}

/**
 * What applies only when the system is the top level of the FPGA.
 * @param {ResolvedNetlist} resolved
 * @param {ExportInfo} info
 */
function topConstraints(resolved, info) {
  const entity = resolved.entity;
  /** @type {string[]} */
  const out = [...headerLines(resolved, info).map((l) => `# ${l}`), '#'];
  out.push(
    ...comment('#', `Constraints of ${entity} as the top level of the FPGA (or in a build of the system on its own): the clocks of its clock ports and the I/O registers. A design around the system creates its clocks and places its I/O registers itself and does not read this file. Pin locations and I/O standards belong to the board.`),
  );
  const top = resolved.clocks.filter((c) => c.source === 'top');
  if (top.length) {
    out.push('', '# Clocks');
    for (const c of top) {
      out.push(`create_clock -period ${(1e9 / c.frequencyHz).toFixed(3)} -name ${c.actual} [get_ports ${c.actual}]`);
    }
  }
  for (const c of resolved.constraints.filter((x) => x.kind === 'io_register')) {
    out.push('', ...comment('#', c.note), `set_property IOB TRUE ${portList(c.ports)}`);
  }
  out.push('');
  return out.join('\n');
}

/**
 * Differences between two resolved netlists of the same system, one line each (empty when they are equal apart from
 * the catalog version): what a new resolution of an older file would change.
 * @param {ResolvedNetlist} before
 * @param {ResolvedNetlist} after
 */
export function netlistDiff(before, after) {
  /** @type {string[]} */
  const out = [];
  if (before.entity !== after.entity) out.push(`Entity: ${before.entity} becomes ${after.entity}.`);
  /**
   * @template T
   * @param {string} what
   * @param {T[]} a
   * @param {T[]} b
   * @param {(x: T) => string} key
   * @param {(x: T) => string} text
   */
  const keyed = (what, a, b, key, text) => {
    const ma = new Map(a.map((x) => [key(x), x]));
    const mb = new Map(b.map((x) => [key(x), x]));
    for (const [k, x] of ma) {
      const y = mb.get(k);
      if (!y) out.push(`${what} ${k}: removed.`);
      else if (text(x) !== text(y)) out.push(`${what} ${k}: ${text(x)} becomes ${text(y)}.`);
    }
    for (const k of mb.keys()) if (!ma.has(k)) out.push(`${what} ${k}: added (${text(/** @type {T} */ (mb.get(k)))}).`);
  };
  keyed('Port', before.ports, after.ports, (p) => p.name, (p) => `${p.dir} ${p.type}`);
  keyed('Instance', before.instances, after.instances, (i) => i.id, (i) => `${i.library}.${i.entity}`);
  for (const a of before.instances) {
    const b = after.instances.find((x) => x.id === a.id);
    if (!b) continue;
    keyed('Generic', a.generics, b.generics, (g) => `${a.id}.${g.name}`, (g) => g.vhdl);
    keyed('Port map', a.ports, b.ports, (p) => `${a.id}.${p.name}`, (p) => (p.useDefault ? `default ${p.default}` : String(p.actual)));
  }
  keyed('Signal', before.signals, after.signals, (s) => s.name, (s) => s.type);
  keyed('Assignment to', before.nets, after.nets, (n) => n.to, (n) => n.from);
  keyed('Library', before.compile, after.compile, (c) => c.library, (c) => `${c.url} ${c.tag ? `${c.tag} ` : ''}${c.commit}`);
  keyed('Clock', before.clocks, after.clocks, (c) => c.id, (c) => `${c.actual} ${c.frequencyHz} Hz`);
  keyed('Reset generator of', before.resets, after.resets, (r) => r.domain, (r) => r.generator);
  const ca = before.constraints.map((c) => JSON.stringify(c));
  const cb = after.constraints.map((c) => JSON.stringify(c));
  for (const c of ca) if (!cb.includes(c)) out.push(`Constraint removed: ${c}`);
  for (const c of cb) if (!ca.includes(c)) out.push(`Constraint added: ${c}`);
  if (JSON.stringify(before.context) !== JSON.stringify(after.context)) out.push(`Context clause: ${after.context.join(' ')}`);
  if (JSON.stringify(before.packing) !== JSON.stringify(after.packing)) out.push('Packing of the data words changed.');
  return out;
}

/**
 * Description and connections of a system and of its subsystem definitions, for the comments of the export.
 * @param {import('./design.js').Design} d
 * @returns {Pick<ExportInfo, 'description' | 'connections' | 'subsystems'>}
 */
export function designComments(d) {
  const conns = (/** @type {import('./design.js').Design} */ x) => x.connections.map((c) => ({ id: c.id, from: c.from, to: c.to }));
  /** @type {Pick<ExportInfo, 'description' | 'connections' | 'subsystems'>} */
  const out = { description: d.description, connections: conns(d) };
  if (d.subsystems) {
    out.subsystems = Object.fromEntries(Object.entries(d.subsystems).map(([n, s]) => [n, { description: s.description, connections: conns(s) }]));
  }
  return out;
}

/**
 * The files of the export of a system.
 * @param {Catalog} cat
 * @param {ResolvedNetlist} resolved
 * @param {ExportInfo} info
 * @returns {{ files: HdlFile[], problems: string[] }}   problems: what keeps the export from being complete
 */
export function exportHdl(cat, resolved, info) {
  /** @type {string[]} */
  const problems = [...resolved.problems];
  const entity = resolved.entity;
  const files = [
    { name: `${entity}.vhd`, text: topLevel(cat, resolved, info) },
    { name: `${entity}_compile_order.txt`, text: compileOrder(cat, resolved, info, problems) },
    { name: `${entity}.xdc`, text: exceptions(resolved, info) },
    { name: `${entity}_top.xdc`, text: topConstraints(resolved, info) },
  ];
  for (const s of resolved.subsystems ?? []) {
    problems.push(...s.netlist.problems.map((x) => `${s.name}/${x}`));
    const own = { ...info, description: info.subsystems?.[s.name]?.description, connections: info.subsystems?.[s.name]?.connections };
    files.push({ name: `${s.name}.vhd`, text: topLevel(cat, s.netlist, own, entity) });
    files.push({ name: `${s.name}.xdc`, text: exceptions(s.netlist, own, entity) });
  }
  return { files, problems };
}
